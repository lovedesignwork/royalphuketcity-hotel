export function getLocalizedMiceType(slug: string, locale: Locale): MiceEventTypeDetail | undefined {
  const base = MICE_EVENT_TYPES[slug];
  if (!base) return undefined;
  if (locale !== "th") return base;
  const copy = miceTh[slug];
  if (!copy) return base;
  return {
    ...base,
    ...copy,
    venueOptions: copy.venueOptions.map((item, index) => ({
      ...item,
      name: base.venueOptions[index]?.name || item.name,
    })),
  };
}

export function getLocalizedMiceTypes(locale: Locale) {
  return Object.keys(MICE_EVENT_TYPES)
    .map((slug) => getLocalizedMiceType(slug, locale))
    .filter((item): item is MiceEventTypeDetail => Boolean(item));
}
